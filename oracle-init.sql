-- Runs once, as SYSDBA in the CDB, on the first container start.

-- LogMiner needs ARCHIVELOG mode and minimal supplemental logging.
ALTER SYSTEM SET db_recovery_file_dest_size = 10G SCOPE=BOTH;
SHUTDOWN IMMEDIATE;
STARTUP MOUNT;
ALTER DATABASE ARCHIVELOG;
ALTER DATABASE OPEN;
ALTER PLUGGABLE DATABASE ALL OPEN;
ALTER DATABASE ADD SUPPLEMENTAL LOG DATA;

-- Connector user, grants as in the Debezium Oracle documentation.
CREATE USER C##DBZUSER IDENTIFIED BY dbz DEFAULT TABLESPACE USERS QUOTA UNLIMITED ON USERS CONTAINER=ALL;
GRANT CREATE SESSION, SET CONTAINER, SELECT ANY TABLE, SELECT ANY TRANSACTION, SELECT ANY DICTIONARY,
      SELECT_CATALOG_ROLE, EXECUTE_CATALOG_ROLE, LOGMINING, FLASHBACK ANY TABLE, CREATE TABLE, LOCK ANY TABLE
  TO C##DBZUSER CONTAINER=ALL;
GRANT EXECUTE ON DBMS_LOGMNR TO C##DBZUSER CONTAINER=ALL;
GRANT EXECUTE ON DBMS_LOGMNR_D TO C##DBZUSER CONTAINER=ALL;

-- One captured table: composite key and a CLOB.
ALTER SESSION SET CONTAINER = FREEPDB1;
CREATE USER APP IDENTIFIED BY app QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION TO APP;
CREATE TABLE APP.EVENTS (
  EV_SITE VARCHAR2(10) NOT NULL,
  EV_ID       NUMBER       NOT NULL,
  EV_NAME     VARCHAR2(100),
  EV_NOTE     VARCHAR2(100),  -- changed by updates that leave the CLOB alone
  EV_DATA     CLOB,
  CONSTRAINT PK_EVENTS PRIMARY KEY (EV_SITE, EV_ID)
);
CREATE SEQUENCE APP.EVENTS_SEQ;
ALTER TABLE APP.EVENTS ADD SUPPLEMENTAL LOG DATA (ALL) COLUMNS;

-- A schema the connector does not capture; the reorg scenario runs a long mass change in it.
CREATE USER REORG IDENTIFIED BY reorg QUOTA UNLIMITED ON USERS;
GRANT CREATE SESSION TO REORG;
CREATE TABLE REORG.JUNK (ID NUMBER, PAD VARCHAR2(2000));
